-- Change the default Omarchy look'n'feel.

-- Sharp corners (rounding 0) and tight outer margins on the left and right
-- edges. The top margin stays at 10px so windows clear the bar.
-- gaps_out uses a table with top/right/bottom/left fields.
hl.config({
  general = {
    gaps_out = { top = 10, right = 0, bottom = 4, left = 0 },
  },
  decoration = {
    rounding = 0,
  },
})

